import fs from 'node:fs/promises';
import {credentialSet} from './credentials.mjs';
import {u256} from './encoding.mjs';
import {nativeToScVal} from '@stellar/stellar-sdk';
import {relayer,invoke,ledgerTime,clean} from './testnet.mjs';
const now=await ledgerTime();
const DEMO_LIFETIME_SECONDS=30*86400;
const set=credentialSet(Math.floor(now/300),30*288);
const financial=await relayer('financial-issuer');
const buyerGate=JSON.parse(await fs.readFile('docs/evidence/gate-b.json','utf8')).contractId;
const dealGate=JSON.parse(await fs.readFile('docs/evidence/gate-c.json','utf8')).contractId;
const registration=await invoke(financial,buyerGate,'register_root',[u256(set.root),nativeToScVal(BigInt(now+DEMO_LIFETIME_SECONDS),{type:'u64'})],'publish synthetic demo credential batch');
const keys={};
for(const [role,name] of Object.entries({admin:'testnet-relayer',financial:'financial-issuer',property:'property-issuer',buyer:'demo-buyer',seller:'demo-seller'})) keys[role]=(await relayer(name)).secret();
const bundle=JSON.stringify({keys,set,buyerGate,dealGate,rootExpires:now+DEMO_LIFETIME_SECONDS,registration:clean(registration)},(_,v)=>typeof v==='bigint'?v.toString():v);
await fs.writeFile('.local/worker-secrets.json',JSON.stringify({DEMO_BUNDLE:bundle}),{mode:0o600});
await fs.writeFile('.dev.vars',`DEMO_BUNDLE='${bundle}'\n`,{mode:0o600});
await fs.mkdir('public/proof',{recursive:true});
await fs.copyFile('.build/eligibility/BalanceEligibility_js/BalanceEligibility.wasm','public/proof/eligibility.wasm');
await fs.copyFile('.build/eligibility/eligibility_final.zkey','public/proof/eligibility.zkey');
await fs.writeFile('docs/evidence/demo-issuance.json',JSON.stringify({network:'Stellar Testnet',recordedAt:new Date().toISOString(),buyerGate,dealGate,issuerRoot:set.root.toString(),rootExpires:now+DEMO_LIFETIME_SECONDS,registration:clean(registration)},null,2)+'\n');
console.log('Demo bundle saved privately; browser proving assets prepared. No private credential was written to public assets.');
process.exit(0);
